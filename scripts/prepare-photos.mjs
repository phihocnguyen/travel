async function rawPreview(file){
 const buffer=await fs.readFile(file),candidates=[];
 for(let start=buffer.indexOf(Buffer.from([255,216]));start!==-1;start=buffer.indexOf(Buffer.from([255,216]),start+2)){
  const end=buffer.indexOf(Buffer.from([255,217]),start+2);if(end<0)continue;
  const data=buffer.subarray(start,end+2);
  try{const m=await sharp(data).metadata();if(m.width>200&&m.height>200)candidates.push({data,area:m.width*m.height});}catch{}
 }
 candidates.sort((a,b)=>b.area-a.area);
 if(!candidates.length)throw new Error(`Cannot read embedded JPEG: ${path.basename(file)}`);
 return candidates[0].data;
}
